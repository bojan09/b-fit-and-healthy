const reps = (
  exerciseSlug: string,
  sets = 3,
  repMin = 8,
  repMax = 12,
  restSeconds = 90,
): WorkoutPrescription => ({
  exerciseSlug,
  sets,
  repMin,
  repMax,
  durationSeconds: null,
  restSeconds,
});

const timed = (
  exerciseSlug: string,
  durationSeconds = 40,
  restSeconds = 20,
): WorkoutPrescription => ({
  exerciseSlug,
  sets: 1,
  repMin: null,
  repMax: null,
  durationSeconds,
  restSeconds,
});

